export function getDepartmentByCode(code: string): FrenchDepartmentInfo | undefined {
  const clean = String(code).trim().toUpperCase();
  return FRENCH_DEPARTMENTS.find(d => d.code === clean || d.code === clean.padStart(2, '0'));
}

export function getDepartmentByName(name: string): FrenchDepartmentInfo | undefined {
  const q = name.toLowerCase().trim();
  return FRENCH_DEPARTMENTS.find(d => 
    d.name.toLowerCase() === q || 
    `${d.code} - ${d.name}`.toLowerCase() === q ||
    d.name.toLowerCase().includes(q)
  );
}

export function getDepartmentsByRegion(regionName: string): FrenchDepartmentInfo[] {
  const q = regionName.toLowerCase().trim();
  return FRENCH_DEPARTMENTS.filter(d => 
    d.region.toLowerCase() === q || 
    d.region.toLowerCase().includes(q)
  );
}

export function getRegionById(regionId: string): FrenchRegionInfo | undefined {
  const clean = regionId.trim().toUpperCase();
  return FRENCH_REGIONS.find(r => r.id === clean || r.name.toLowerCase() === regionId.toLowerCase().trim());
}

/**
 * Finds best matching department for a given station
 */
export function findDepartmentForStation(station: { department?: string; region?: string; name?: string; latitude?: number; longitude?: number }): FrenchDepartmentInfo {
  // 1. Try parsing station.department (e.g. "75 - Paris", "69 - Rhône", "13 - Bouches-du-Rhône")
  if (station.department) {
    const codeMatch = station.department.match(/^(\d{2,3}|2A|2B)/i);
    if (codeMatch) {
      const found = getDepartmentByCode(codeMatch[1]);
      if (found) return found;
    }
    const foundByName = getDepartmentByName(station.department);
    if (foundByName) return foundByName;
  }

  // 2. Try matching region + name
  if (station.name) {
    const foundByStationName = FRENCH_DEPARTMENTS.find(d => 
      station.name!.toLowerCase().includes(d.name.toLowerCase()) ||
      station.name!.toLowerCase().includes(d.prefecture.toLowerCase())
    );
    if (foundByStationName) return foundByStationName;
  }

  // 3. Try closest geographic distance
  if (typeof station.latitude === 'number' && typeof station.longitude === 'number') {
    let closestDept = FRENCH_DEPARTMENTS[0];
    let minDistance = Infinity;

    for (const dept of FRENCH_DEPARTMENTS) {
      const dLat = dept.latitude - station.latitude;
      const dLon = dept.longitude - station.longitude;
      const dist = dLat * dLat + dLon * dLon;
      if (dist < minDistance) {
        minDistance = dist;
        closestDept = dept;
      }
    }
    return closestDept;
  }

  // Default to Paris
  return FRENCH_DEPARTMENTS.find(d => d.code === '75') || FRENCH_DEPARTMENTS[0];
}
