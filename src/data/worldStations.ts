export function getWorldStationById(id: string): WorldCityPoint | undefined {
  return WORLD_STATIONS.find(s => s.id === id);
}

export function searchWorldStations(query: string): WorldCityPoint[] {
  if (!query || query.trim().length === 0) return WORLD_STATIONS;
  const q = query.toLowerCase().trim();
  return WORLD_STATIONS.filter(s => 
    s.name.toLowerCase().includes(q) ||
    s.country.toLowerCase().includes(q) ||
    s.continent.toLowerCase().includes(q) ||
    s.climateZone.toLowerCase().includes(q)
  );
}
