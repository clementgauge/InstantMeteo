const WORD_REGEX = /([ldqunsjcLDQUNSJC]['’])?([a-zA-ZÀ-ÿœŒæÆ]{2,})/g;

function preserveCase(sourceWord: string, translatedWord: string): string {
  if (!sourceWord || !translatedWord) return translatedWord;
  if (sourceWord === sourceWord.toUpperCase() && sourceWord !== sourceWord.toLowerCase()) {
    return translatedWord.toUpperCase();
  }
  const firstChar = sourceWord[0];
  if (firstChar === firstChar.toUpperCase() && firstChar !== firstChar.toLowerCase()) {
    return translatedWord.charAt(0).toUpperCase() + translatedWord.slice(1);
  }
  return translatedWord;
}

export function translateStringToEn(input: string): string {
  if (!input) return input;
  const trimmed = input.trim();
  if (!trimmed) return input;

  // Stage 1: Exact UI string match
  if (FR_TO_EN_EXACT[trimmed]) {
    return input.replace(trimmed, FR_TO_EN_EXACT[trimmed]);
  }

  let out = input;

  // Stage 2: Longest-first multi-word meteorological & UI phrases
  for (const [regex, replacement] of SORTED_PHRASE_REGEXES) {
    out = out.replace(regex, replacement);
  }

  // Clean common French prepositional connectors before Stage 3 word lookup
  out = out
    .replace(/\bdu\b/gi, 'of the')
    .replace(/\bdes\b/gi, 'of')
    .replace(/\bau\b/gi, 'at')
    .replace(/\baux\b/gi, 'to')
    .replace(/\bde la\b/gi, 'of the')
    .replace(/\bde l['’]/gi, 'of ')
    .replace(/\bd['’]/gi, 'of ')
    .replace(/\bl['’]/gi, 'the ')
    .replace(/\bde\b/gi, 'of')
    .replace(/(?<![a-zA-ZÀ-ÿœŒæÆ])à(?![a-zA-ZÀ-ÿœŒæÆ])/gi, 'to');

  // Stage 3: Word-by-word dictionary translation with capitalization preservation
  out = out.replace(WORD_REGEX, (fullMatch, prefix: string | undefined, word: string) => {
    const lower = word.toLowerCase();
    // Skip common articles if already in English or short French articles before translated words
    if (lower === 'le' || lower === 'la' || lower === 'les') {
      return preserveCase(word, 'the');
    }
    if (lower === 'un' || lower === 'une') {
      return preserveCase(word, 'a');
    }
    const mapped = FR_TO_EN_WORD_MAP[lower];
    if (!mapped) return fullMatch;
    const cased = preserveCase(word, mapped);
    if (prefix) {
      const pLower = prefix[0].toLowerCase();
      if (pLower === 'l') return `the ${cased}`;
      if (pLower === 'd') return `of ${cased}`;
    }
    return cased;
  });

  // Polish minor duplicate articles ("of the the " -> "of the ")
  out = out
    .replace(/\b(the|of)\s+\1\b/gi, '$1')
    .replace(/\bof the\s+the\b/gi, 'of the');

  return out;
}

interface TrackedTextState {
  fr: string;
  en: string;
}

const trackedTextNodes = new WeakMap<Text, TrackedTextState>();
const trackedAttributes = new WeakMap<Element, Record<string, TrackedTextState>>();
let currentNativeLang: NativeSiteLang = 'fr';
let domObserver: MutationObserver | null = null;
let isApplyingTranslation = false;
let pendingFrame: number | null = null;

function processNodeForLanguage(root: Node, lang: NativeSiteLang) {
  if (typeof document === 'undefined' || !root) return;
  isApplyingTranslation = true;
  try {
    // Handle direct Text node if passed directly
    if (root.nodeType === Node.TEXT_NODE) {
      const tNode = root as Text;
      const parent = tNode.parentElement;
      if (
        parent &&
        parent.tagName !== 'SCRIPT' &&
        parent.tagName !== 'STYLE' &&
        parent.tagName !== 'NOSCRIPT' &&
        parent.tagName !== 'TEXTAREA' &&
        !parent.closest('#google-translate-custom-control')
      ) {
        applyTextNodeTranslation(tNode, lang);
      }
      return;
    }

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName;
        if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT' || tag === 'TEXTAREA') {
          return NodeFilter.FILTER_REJECT;
        }
        if (parent.closest('#google-translate-custom-control')) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    });

    const textNodes: Text[] = [];
    let current = walker.nextNode();
    while (current) {
      textNodes.push(current as Text);
      current = walker.nextNode();
    }

    for (const tNode of textNodes) {
      applyTextNodeTranslation(tNode, lang);
    }

    if (root instanceof Element || root instanceof Document) {
      const elements =
        (root as ParentNode).querySelectorAll?.('[placeholder], [title], [aria-label], [alt]') || [];
      elements.forEach((el) => {
        if (el.closest('#google-translate-custom-control')) return;
        applyElementAttributeTranslation(el, lang);
      });
      if (root instanceof Element && !root.closest('#google-translate-custom-control')) {
        applyElementAttributeTranslation(root, lang);
      }
    }
  } finally {
    isApplyingTranslation = false;
  }
}

function applyTextNodeTranslation(tNode: Text, lang: NativeSiteLang) {
  const val = tNode.nodeValue || '';
  if (!val.trim()) return;

  const saved = trackedTextNodes.get(tNode);

  if (lang === 'en') {
    // If never translated OR React updated the text node with new French content
    if (!saved || (val !== saved.en && val !== saved.fr)) {
      const enVal = translateStringToEn(val);
      trackedTextNodes.set(tNode, { fr: val, en: enVal });
      if (tNode.nodeValue !== enVal) {
        tNode.nodeValue = enVal;
      }
    } else if (val === saved.fr && val !== saved.en) {
      tNode.nodeValue = saved.en;
    }
  } else {
    if (saved && tNode.nodeValue === saved.en && saved.fr !== saved.en) {
      tNode.nodeValue = saved.fr;
    }
  }
}

function applyElementAttributeTranslation(el: Element, lang: NativeSiteLang) {
  const attrs = ['placeholder', 'title', 'aria-label', 'alt'];
  let savedMap = trackedAttributes.get(el);
  if (!savedMap) {
    savedMap = {};
    trackedAttributes.set(el, savedMap);
  }

  for (const attr of attrs) {
    const curVal = el.getAttribute(attr);
    if (!curVal || !curVal.trim()) continue;
    const saved = savedMap[attr];

    if (lang === 'en') {
      if (!saved || (curVal !== saved.en && curVal !== saved.fr)) {
        const enVal = translateStringToEn(curVal);
        savedMap[attr] = { fr: curVal, en: enVal };
        if (curVal !== enVal) {
          el.setAttribute(attr, enVal);
        }
      } else if (curVal === saved.fr && curVal !== saved.en) {
        el.setAttribute(attr, saved.en);
      }
    } else {
      if (saved && curVal === saved.en && saved.fr !== saved.en) {
        el.setAttribute(attr, saved.fr);
      }
    }
  }
}

export function getNativeSiteLanguage(): NativeSiteLang {
  if (typeof window !== 'undefined') {
    const params = new URLSearchParams(window.location.search);
    const hl = params.get('hl') || params.get('lang');
    if (hl === 'en') return 'en';
  }
  return currentNativeLang;
}

export function applyNativeSiteLanguage(lang: NativeSiteLang): void {
  currentNativeLang = lang;
  if (typeof document === 'undefined' || !document.body) return;

  document.documentElement.lang = lang;
  processNodeForLanguage(document.body, lang);

  if (lang === 'en') {
    if (!domObserver) {
      domObserver = new MutationObserver((mutations) => {
        if (isApplyingTranslation || currentNativeLang !== 'en') return;

        const nodesToProcess = new Set<Node>();
        for (const m of mutations) {
          if (m.type === 'characterData' && m.target) {
            nodesToProcess.add(m.target);
          } else if (m.type === 'attributes' && m.target) {
            nodesToProcess.add(m.target);
          } else if (m.type === 'childList') {
            m.addedNodes.forEach((n) => {
              if (n.nodeType === Node.ELEMENT_NODE || n.nodeType === Node.TEXT_NODE) {
                nodesToProcess.add(n);
              }
            });
          }
        }

        if (nodesToProcess.size > 0) {
          if (pendingFrame !== null) {
            cancelAnimationFrame(pendingFrame);
          }
          pendingFrame = requestAnimationFrame(() => {
            pendingFrame = null;
            if (currentNativeLang !== 'en') return;
            nodesToProcess.forEach((n) => processNodeForLanguage(n, 'en'));
          });
        }
      });

      domObserver.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true,
        attributes: true,
        attributeFilter: ['placeholder', 'title', 'aria-label', 'alt'],
      });
    }
  } else {
    if (pendingFrame !== null) {
      cancelAnimationFrame(pendingFrame);
      pendingFrame = null;
    }
    if (domObserver) {
      domObserver.disconnect();
      domObserver = null;
    }
  }

  window.dispatchEvent(new CustomEvent('instant_meteo_native_lang_change', { detail: { lang } }));
}
